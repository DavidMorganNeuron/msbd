[CmdletBinding()]
param (
    [string] $MatrixPath,
    [string] $OutputPath
)

$ErrorActionPreference = 'Stop'
$repositoryRoot = (Resolve-Path (Join-Path $PSScriptRoot '..\..\..')).Path

if ([string]::IsNullOrWhiteSpace($MatrixPath)) {
    $MatrixPath = Join-Path $PSScriptRoot 'MATRIKS_PRIVILEGE.csv'
} else {
    $MatrixPath = [System.IO.Path]::GetFullPath($MatrixPath)
}

if ([string]::IsNullOrWhiteSpace($OutputPath)) {
    $OutputPath = Join-Path $PSScriptRoot '02_privileges.sql'
} else {
    $OutputPath = [System.IO.Path]::GetFullPath($OutputPath)
}

if (-not (Test-Path -LiteralPath $MatrixPath -PathType Leaf)) {
    throw "Matriks privilege tidak ditemukan: $MatrixPath"
}

$roles = @('role_siswa', 'role_tu', 'role_kepsek', 'role_wali_kelas', 'app_login', 'app_owner')
$matrix = @(Import-Csv -LiteralPath $MatrixPath -Encoding UTF8)
$requiredColumns = @(
    'object_type',
    'object_name',
    'role',
    'privileges',
    'select_columns',
    'insert_columns',
    'update_columns',
    'owner',
    'notes'
)

if ($matrix.Count -eq 0) {
    throw 'Matriks privilege kosong.'
}

foreach ($column in $requiredColumns) {
    if ($null -eq $matrix[0].PSObject.Properties[$column]) {
        throw "Kolom wajib tidak ada pada matriks: $column"
    }
}

$allowedTypes = @('schema', 'table', 'view', 'sequence', 'function', 'trigger_function', 'procedure')
$privilegeByType = @{
    schema = @('USAGE', 'CREATE')
    table = @('SELECT', 'INSERT', 'UPDATE', 'DELETE', 'TRUNCATE', 'REFERENCES', 'TRIGGER')
    view = @('SELECT', 'INSERT', 'UPDATE', 'DELETE', 'TRUNCATE', 'REFERENCES', 'TRIGGER')
    sequence = @('USAGE', 'SELECT', 'UPDATE')
    function = @('EXECUTE')
    trigger_function = @('EXECUTE')
    procedure = @('EXECUTE')
}
$seen = @{}
$objects = @{}

foreach ($row in $matrix) {
    if ($row.object_type -notin $allowedTypes) {
        throw "Jenis objek tidak dikenal: $($row.object_type)"
    }
    if ($row.role -notin $roles) {
        throw "Role tidak dikenal: $($row.role)"
    }
    $validObjectName = $row.object_name -match '^[A-Za-z_][A-Za-z0-9_]*(\([A-Za-z0-9_, ]*\))?$'
    $validQualifiedRoutineName = $row.object_type -in @('function', 'trigger_function', 'procedure') -and
        $row.object_name -match '^[A-Za-z_][A-Za-z0-9_]*\.[A-Za-z_][A-Za-z0-9_]*(\([A-Za-z0-9_, ]*\))?$'
    if (($row.object_name -ne '*' -or $row.object_type -ne 'sequence') -and -not $validObjectName -and -not $validQualifiedRoutineName) {
        throw "Nama objek tidak valid: $($row.object_name)"
    }

    if ($row.object_type -eq 'sequence' -and $row.object_name -eq '*' -and $row.owner) {
        throw 'Baris sequence wildcard tidak dapat memiliki owner.'
    }

    if ($row.object_type -notin @('table', 'schema', 'view', 'sequence') -and ($row.select_columns -or $row.insert_columns -or $row.update_columns)) {
        throw "Nama objek tidak valid: $($row.object_name)"
    }

    $key = '{0}|{1}|{2}' -f $row.object_type, $row.object_name, $row.role
    if ($seen.ContainsKey($key)) {
        throw "Baris matriks duplikat: $key"
    }
    $seen[$key] = $true

    $objectKey = '{0}|{1}' -f $row.object_type, $row.object_name
    if (-not $objects.ContainsKey($objectKey)) {
        $objects[$objectKey] = @()
    }
    $objects[$objectKey] += $row.role

    $privileges = @($row.privileges -split ';' | Where-Object { -not [string]::IsNullOrWhiteSpace($_) })
    foreach ($privilege in $privileges) {
        if ($privilege -cnotin $privilegeByType[$row.object_type]) {
            throw "Privilege $privilege tidak sesuai dengan $($row.object_type) $($row.object_name)."
        }
    }

    if ($row.object_type -in @('function', 'trigger_function', 'procedure') -and $row.owner -and $row.owner -ne 'app_owner') {
        throw "Owner rutin tidak diizinkan: $($row.owner)"
    }
}

foreach ($objectKey in $objects.Keys) {
    $actualRoles = @($objects[$objectKey] | Sort-Object -Unique)
    if ($actualRoles.Count -ne $roles.Count -or @($roles | Where-Object { $_ -notin $actualRoles }).Count -gt 0) {
        throw "Matriks harus memiliki satu baris untuk setiap role pada objek $objectKey."
    }
}

if (-not $objects.ContainsKey('schema|public')) {
    throw 'Matriks tidak memuat schema public.'
}

$roleList = $roles -join ', '
$columnTables = @(
    $matrix |
        Where-Object { $_.object_type -eq 'table' -and ($_.select_columns -or $_.insert_columns -or $_.update_columns) } |
        Group-Object object_name
)
$lines = @(
    '-- Generated by hasilkan_privilege.ps1 from MATRIKS_PRIVILEGE.csv.',
    '-- Empty matrix cells mean no explicit privilege; row-level isolation is not provided here.',
    '',
    "REVOKE ALL ON SCHEMA public FROM PUBLIC, $roleList;",
    "REVOKE ALL ON ALL TABLES IN SCHEMA public FROM PUBLIC, $roleList;",
    "REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM PUBLIC, $roleList;",
    "GRANT USAGE ON SCHEMA public TO $roleList;"
)

foreach ($row in $matrix | Where-Object { $_.object_type -eq 'schema' -and $_.object_name -ne 'public' } | Select-Object -Unique object_name) {
    $lines += "REVOKE ALL ON SCHEMA $($row.object_name) FROM PUBLIC, $roleList;"
}

foreach ($row in $matrix | Where-Object { $_.object_type -eq 'schema' }) {
    $privileges = @($row.privileges -split ';' | Where-Object { -not [string]::IsNullOrWhiteSpace($_) })
    $extraPrivileges = if ($row.object_name -eq 'public') {
        @($privileges | Where-Object { $_.ToUpperInvariant() -ne 'USAGE' } | Sort-Object -Unique)
    } else {
        @($privileges | Sort-Object -Unique)
    }
    if ($extraPrivileges.Count -gt 0) {
        $lines += 'GRANT ' + ($extraPrivileges -join ', ') + " ON SCHEMA $($row.object_name) TO $($row.role);"
    }
}

foreach ($group in $columnTables) {
    $columns = @(
        $group.Group |
            ForEach-Object { @($_.select_columns, $_.insert_columns, $_.update_columns) } |
            ForEach-Object { $_ -split ',' } |
            ForEach-Object { $_.Trim() } |
            Where-Object { $_ } |
            Sort-Object -Unique
    )
    $lines += 'REVOKE ALL (' + ($columns -join ', ') + ") ON TABLE public.$($group.Name) FROM PUBLIC, $roleList;"
}

$routines = @($matrix | Where-Object { $_.object_type -in @('function', 'trigger_function', 'procedure') })
foreach ($group in ($routines | Group-Object object_type, object_name)) {
    $row = $group.Group[0]
    $routineType = if ($row.object_type -eq 'procedure') { 'PROCEDURE' } else { 'FUNCTION' }
    $signature = if ($row.object_name.Contains('.')) { $row.object_name } else { 'public.' + $row.object_name }
    $lines += "REVOKE ALL ON $routineType $signature FROM PUBLIC, $roleList;"
}

foreach ($row in $matrix | Sort-Object object_type, object_name, role) {
    $privileges = @($row.privileges -split ';' | Where-Object { -not [string]::IsNullOrWhiteSpace($_) } | Sort-Object -Unique)
    $privileges = @($privileges | ForEach-Object { $_.ToUpperInvariant() })
    $object = $null

    if ($row.object_type -eq 'schema') {
        continue
    }

    if ($row.object_type -eq 'sequence' -and $row.object_name -eq '*') {
        if ($privileges.Count -gt 0) {
            $lines += 'GRANT ' + ($privileges -join ', ') + " ON ALL SEQUENCES IN SCHEMA public TO $($row.role);"
        }
        continue
    }

    switch ($row.object_type) {
        'schema' {
            $object = 'SCHEMA public'
        }
        'table' {
            $object = 'TABLE public.' + $row.object_name
        }
        'view' {
            $object = 'TABLE public.' + $row.object_name
        }
        'sequence' {
            $object = 'SEQUENCE public.' + $row.object_name
        }
        'function' {
            $object = if ($row.object_name.Contains('.')) { 'FUNCTION ' + $row.object_name } else { 'FUNCTION public.' + $row.object_name }
        }
        'trigger_function' {
            $object = if ($row.object_name.Contains('.')) { 'FUNCTION ' + $row.object_name } else { 'FUNCTION public.' + $row.object_name }
        }
        'procedure' {
            $object = if ($row.object_name.Contains('.')) { 'PROCEDURE ' + $row.object_name } else { 'PROCEDURE public.' + $row.object_name }
        }
    }

    if ($privileges.Count -gt 0) {
        $lines += 'GRANT ' + ($privileges -join ', ') + " ON $object TO $($row.role);"
    }

    foreach ($columnPrivilege in @(
        @{ Privilege = 'SELECT'; Columns = $row.select_columns },
        @{ Privilege = 'INSERT'; Columns = $row.insert_columns },
        @{ Privilege = 'UPDATE'; Columns = $row.update_columns }
    )) {
        $columns = @($columnPrivilege.Columns -split ',' | ForEach-Object { $_.Trim() } | Where-Object { $_ })
        if ($columns.Count -gt 0) {
            if ($row.object_type -ne 'table') {
                throw "Kolom hanya boleh dicantumkan untuk tabel: $($row.object_name)"
            }
            foreach ($column in $columns) {
                if ($column -notmatch '^[A-Za-z_][A-Za-z0-9_]*$') {
                    throw "Nama kolom tidak valid: $column"
                }
            }
            $lines += "GRANT $($columnPrivilege.Privilege) (" + ($columns -join ', ') + ") ON TABLE public.$($row.object_name) TO $($row.role);"
        }
    }

    if ($row.owner) {
        $routineType = if ($row.object_type -eq 'procedure') { 'PROCEDURE' } else { 'FUNCTION' }
        $signature = if ($row.object_name.Contains('.')) { $row.object_name } else { 'public.' + $row.object_name }
        $lines += "ALTER $routineType $signature OWNER TO $($row.owner);"
    }
}

Set-Content -LiteralPath $OutputPath -Value $lines -Encoding UTF8

Write-Output "matrix_rows=$($matrix.Count)"
Write-Output "objects=$($objects.Count)"
Write-Output "output=$OutputPath"
